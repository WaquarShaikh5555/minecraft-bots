#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
#  One-shot installer for an Ubuntu VM (Azure for Students, or any VPS).
#
#  Run as root on the VM:
#
#    curl -fsSL https://raw.githubusercontent.com/WaquarShaikh5555/minecraft-bots/main/deploy/setup-azure-vm.sh \
#      | sudo bash -s -- --bot-name waquar5555 --server world.arterex.me:25565
#
#  Or, if you already cloned the repo on the VM:
#
#    sudo bash deploy/setup-azure-vm.sh --tunnel
#
#  What it does: Node 22 -> system user -> /opt/minecraft-bots -> .env with a
#  generated chat token -> systemd service that restarts on crash and on boot.
#  It is idempotent: run it again after changing flags to reconfigure.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

REPO="https://github.com/WaquarShaikh5555/minecraft-bots.git"
BRANCH="main"
APP_DIR="/opt/minecraft-bots"
SERVICE="minecraft-bot"
RUN_USER="minecraft"
BOT_NAME="waquar5555"
SERVER="world.arterex.me:25565"
AUTH="offline"
PORT="8080"
ANON="false"
SWITCH="false"
INSTALL_TUNNEL="false"
NODE_MAJOR=22

say()  { printf '\033[36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[33m!!\033[0m %s\n' "$*"; }
die()  { printf '\033[31mxx\033[0m %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<USAGE
Usage: sudo bash setup-azure-vm.sh [options]

  --bot-name NAME     in-game name of the bot          (default: $BOT_NAME)
  --server HOST:PORT  server to join, repeatable/comma separated (default: $SERVER)
  --auth MODE         offline | microsoft              (default: $AUTH)
  --port PORT         dashboard port                   (default: $PORT)
  --repo URL          git repo to deploy               (default: this repo)
  --branch NAME       branch to deploy                 (default: $BRANCH)
  --dir PATH          install directory                (default: $APP_DIR)
  --allow-anonymous   let anyone chat without a token  (default: off)
  --allow-switch      let the site move the bot between servers (default: off)
  --tunnel            also install a free Cloudflare quick tunnel (HTTPS + WSS)
  -h, --help          show this help
USAGE
  exit 0
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --bot-name)        BOT_NAME="$2"; shift 2 ;;
    --server)          SERVER="$2"; shift 2 ;;
    --auth)            AUTH="$2"; shift 2 ;;
    --port)            PORT="$2"; shift 2 ;;
    --repo)            REPO="$2"; shift 2 ;;
    --branch)          BRANCH="$2"; shift 2 ;;
    --dir)             APP_DIR="$2"; shift 2 ;;
    --allow-anonymous) ANON="true"; shift ;;
    --allow-switch)    SWITCH="true"; shift ;;
    --tunnel)          INSTALL_TUNNEL="true"; shift ;;
    -h|--help)         usage ;;
    *)                 die "Unknown option: $1 (try --help)" ;;
  esac
done

[[ $EUID -eq 0 ]] || die "Run this as root: sudo bash $0 $*"
command -v curl >/dev/null || die "curl is required"

# ── 1. Node.js ───────────────────────────────────────────────────────────────
if command -v node >/dev/null && [[ "$(node -v | cut -d. -f1 | tr -d v)" -ge 20 ]]; then
  say "Node $(node -v) already installed"
else
  say "Installing Node.js $NODE_MAJOR"
  if [[ -f /etc/debian_version ]]; then
    curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash -
    apt-get install -y nodejs git
  else
    warn "Not Debian/Ubuntu — install Node 20+ and git yourself, then re-run."
    exit 1
  fi
fi
command -v git >/dev/null || apt-get install -y git

# ── 2. Service user ──────────────────────────────────────────────────────────
if ! id -u "$RUN_USER" >/dev/null 2>&1; then
  say "Creating system user '$RUN_USER'"
  useradd --system --home "$APP_DIR" --shell /usr/sbin/nologin "$RUN_USER"
fi

# ── 3. Code ──────────────────────────────────────────────────────────────────
if [[ -d "$APP_DIR/.git" ]]; then
  say "Updating $APP_DIR"
  git -C "$APP_DIR" fetch --prune origin
  git -C "$APP_DIR" checkout "$BRANCH"
  git -C "$APP_DIR" reset --hard "origin/$BRANCH"
else
  say "Cloning $REPO ($BRANCH) into $APP_DIR"
  mkdir -p "$APP_DIR"
  git clone --branch "$BRANCH" --depth 1 "$REPO" "$APP_DIR"
fi

cd "$APP_DIR"
# npm must be able to write node_modules and its cache as the service user.
mkdir -p data .mc-profiles
chown -R "$RUN_USER:$RUN_USER" "$APP_DIR"

say "Installing production dependencies"
sudo -u "$RUN_USER" -H npm ci --omit=dev --no-audit --no-fund 2>/dev/null \
  || sudo -u "$RUN_USER" -H npm install --omit=dev --no-audit --no-fund

# ── 4. Configuration ─────────────────────────────────────────────────────────
if [[ ! -f .env ]]; then
  TOKEN="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  say "Writing .env (chat token generated)"
  cat > .env <<ENV
# Generated by deploy/setup-azure-vm.sh on $(date -u +%Y-%m-%dT%H:%MZ)
MC_USERNAME=${BOT_NAME}
MC_SERVERS=${SERVER}
MC_AUTH=${AUTH}
MC_SKIP_VALIDATION=true

PORT=${PORT}
HOST=0.0.0.0
CHAT_TOKEN=${TOKEN}
ALLOW_ANONYMOUS_CHAT=${ANON}
ALLOW_SERVER_SWITCH=${SWITCH}
ALLOWED_ORIGINS=

CHAT_HISTORY=400
CHAT_LOG_FILE=data/chat.jsonl
RECONNECT=true
LOG_LEVEL=info
ENV
  chmod 600 .env
  echo
  echo "   ┌──────────────────────────────────────────────────────────────┐"
  echo "   │  CHAT_TOKEN=${TOKEN}"
  echo "   │  Save it now — you need it to send chat from the website.    │"
  echo "   └──────────────────────────────────────────────────────────────┘"
  echo
else
  warn ".env already exists — leaving it untouched (edit it, then: systemctl restart $SERVICE)"
  # Still apply the flags that are safe to refresh.
  sed -i "s|^MC_USERNAME=.*|MC_USERNAME=${BOT_NAME}|" .env
  sed -i "s|^MC_SERVERS=.*|MC_SERVERS=${SERVER}|" .env
  sed -i "s|^MC_AUTH=.*|MC_AUTH=${AUTH}|" .env
  sed -i "s|^PORT=.*|PORT=${PORT}|" .env
fi

mkdir -p data .mc-profiles
chown -R "$RUN_USER:$RUN_USER" "$APP_DIR"

# ── 5. systemd service ───────────────────────────────────────────────────────
say "Installing systemd service"
sed -e "s|/opt/minecraft-bots|${APP_DIR}|g" \
    -e "s|^User=.*|User=${RUN_USER}|" \
    -e "s|^Group=.*|Group=${RUN_USER}|" \
    deploy/systemd/minecraft-bot.service > "/etc/systemd/system/${SERVICE}.service"
systemctl daemon-reload
systemctl enable "$SERVICE" >/dev/null 2>&1
systemctl restart "$SERVICE"

# ── 6. Optional free HTTPS tunnel ────────────────────────────────────────────
if [[ "$INSTALL_TUNNEL" == "true" ]]; then
  if ! command -v cloudflared >/dev/null; then
    say "Installing cloudflared"
    curl -fsSL -o /usr/local/bin/cloudflared \
      https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64
    chmod +x /usr/local/bin/cloudflared
  fi
  cat > /etc/systemd/system/cloudflared-quick.service <<TUNNEL
[Unit]
Description=Cloudflare quick tunnel to the Minecraft bot dashboard
After=network-online.target ${SERVICE}.service

[Service]
ExecStart=/usr/local/bin/cloudflared tunnel --no-autoupdate --url http://127.0.0.1:${PORT}
Restart=always
RestartSec=5
User=${RUN_USER}

[Install]
WantedBy=multi-user.target
TUNNEL
  systemctl daemon-reload
  systemctl enable --now cloudflared-quick
  say "Tunnel starting — get its public https:// URL with:"
  echo "     journalctl -u cloudflared-quick -n 40 --no-pager | grep -o 'https://[a-z0-9-]*\\.trycloudflare\\.com'"
  warn "Quick tunnels get a NEW random URL on every restart. For a permanent address"
  warn "use docs/free-hosting.md → 'Named Cloudflare Tunnel' or nginx + certbot."
fi

# ── 7. Summary ───────────────────────────────────────────────────────────────
sleep 3
say "Status"
systemctl --no-pager --lines=5 status "$SERVICE" || true
echo
IP="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || echo '<your-vm-public-ip>')"
cat <<DONE

──────────────────────────────────────────────────────────────────────────
  Done.

  Dashboard on the VM : http://127.0.0.1:${PORT}
  Dashboard publicly  : http://${IP}:${PORT}
                        (open TCP ${PORT} in the Azure NSG / firewall first)
  Bot                 : ${BOT_NAME} → ${SERVER} (${AUTH} mode)
  Service             : systemctl status ${SERVICE}
  Live logs           : journalctl -u ${SERVICE} -f
  Chat log file       : ${APP_DIR}/data/chat.jsonl

  Next: docs/azure-vm.md (network rules) and docs/free-hosting.md (HTTPS).
──────────────────────────────────────────────────────────────────────────
DONE

if [[ "$AUTH" == "microsoft" ]]; then
  warn "MC_AUTH=microsoft — sign in once on the VM:"
  echo "     cd ${APP_DIR} && sudo -u ${RUN_USER} npm run login:microsoft"
fi
